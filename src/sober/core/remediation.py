"""
Remediation Prompt Generator for SOBER.
Synthesizes high-density, zero-hallucination markdown prompts to feed directly
into autonomous coding agents (Claude Code, Cursor Agent, Copilot Workspace, Aider, Devin).
"""

from sober.detectors import Issue, Severity


def generate_agent_remediation_prompt(
    issues: list[Issue],
    score: float,
    grade: str,
    status_label: str,
    files_scanned: int,
) -> str:
    """Generate high-density context prompt instructing an AI agent to fix hangover defects."""
    if not issues:
        return (
            "## 🍸 SOBER AUDIT: ALL CHECKS PASSED\n\n"
            f"Sobriety Score: {score}% ({grade}) • {status_label}\n"
            f"Scanned {files_scanned} files. No AI hangover debris or vulnerabilities found.\n"
        )

    critical_count = sum(1 for i in issues if i.severity == Severity.CRITICAL)
    high_count = sum(1 for i in issues if i.severity == Severity.HIGH)
    medium_count = sum(1 for i in issues if i.severity == Severity.MEDIUM)
    low_count = sum(1 for i in issues if i.severity == Severity.LOW)

    lines = [
        "## 🍸 SOBER AGENT REMEDIATION DIRECTIVE",
        "",
        f"**Sobriety Score:** {score}% ({grade}) — {status_label}",
        f"**Issues Detected:** {len(issues)} total ({critical_count} Critical, {high_count} High, {medium_count} Medium, {low_count} Low)",
        "",
        "### INSTRUCTIONS FOR CODING AGENT:",
        "1. Inspect the exact file locations and code snippets listed below.",
        "2. Remediate all issues surgically without altering unrelated business logic.",
        "3. For secrets or API keys: move credentials to environment variables (`.env`).",
        "4. For hallucinated/slopsquatted packages: replace with verified packages or add to manifests.",
        "5. For missing timeouts: add explicit `timeout=30.0` or signal aborts to all HTTP requests.",
        "6. For ghost code/chatter: delete leftover debug logs, breakpoints, and AI comments.",
        "7. For silent except blocks: log exceptions or handle errors explicitly.",
        "",
        "### ACTIONABLE DEFECTS TO CURE:",
        "",
    ]

    for idx, issue in enumerate(issues, start=1):
        lines.append(f"#### {idx}. [{issue.severity.value}] {issue.title}")
        lines.append(f"- **Location:** `{issue.file_path}:{issue.line_number}`")
        lines.append(f"- **Category:** {issue.category}")
        lines.append(f"- **Description:** {issue.description}")
        if issue.code_snippet:
            lines.append(f"- **Current Snippet:**\n```text\n{issue.code_snippet}\n```")
        lines.append(f"- **Prescribed Fix:** {issue.fix_suggestion}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by SOBER - The Vibe Coding Hangover Cure (https://github.com/shenald-dev/sober)*")
    return "\n".join(lines)
