"""
Detector for AI Conversational Chatter, Prompt Leakage, and Assistant Artifacts.
Catches conversational LLM responses accidentally pasted or generated into source files.
"""

import re
from pathlib import Path

from sober.core.scanner import FileToAudit
from sober.detectors import Issue, Severity

CHATTER_PATTERNS = [
    (re.compile(r'^(?:#|//|\*)\s*(?:Certainly!|Sure!|Of course!)\s*(?:Here(?:\'s| is) (?:the|your|an updated))', re.IGNORECASE), "AI conversational greeting in code comment"),
    (re.compile(r'^(?:#|//|\*)\s*Here(?:\'s| is) (?:the|your|an) (?:complete|updated|refactored)?\s*(?:code|implementation|file|function|script)', re.IGNORECASE), "AI conversational introduction in code comment"),
    (re.compile(r'^(?:#|//|\*)\s*As an AI (?:language model|assistant)', re.IGNORECASE), "AI persona disclosure comment"),
    (re.compile(r'^(?:#|//|\*)\s*(?:I hope this helps!|Let me know if you (?:need|have any)|Feel free to ask)', re.IGNORECASE), "AI assistant sign-off comment"),
    (re.compile(r'^(?:#|//|\*)\s*Note:\s*(?:You (?:will need to|can|should)|Make sure to)\s*replace\s*this\s*(?:placeholder|mock|dummy|with your)', re.IGNORECASE), "AI placeholder disclaimer"),
    (re.compile(r'^(?:#|//|\*)\s*(?:Generated by|Output from)\s*(?:Claude|ChatGPT|GPT-4|Cursor|Copilot|Windsurf)', re.IGNORECASE), "AI agent attribution banner"),
]


def audit_chatter(file_audit: FileToAudit, project_root: Path) -> list[Issue]:
    """Scan file for AI conversational chatter, prompt leakage, and assistant artifact comments."""
    issues = []
    code = file_audit.read_text()
    if not code:
        return issues

    file_rel = str(file_audit.path.relative_to(project_root) if file_audit.path.is_relative_to(project_root) else file_audit.path)
    lines = code.splitlines()

    for idx, line in enumerate(lines, start=1):
        if file_audit.diff_lines and idx not in file_audit.diff_lines:
            continue

        stripped = line.strip()
        for pattern, title in CHATTER_PATTERNS:
            if pattern.search(stripped):
                issues.append(
                    Issue(
                        category="AI Conversational Chatter",
                        title=title,
                        description=f"AI conversational text or assistant disclaimer was left in source code: '{stripped[:60]}...'",
                        severity=Severity.LOW,
                        file_path=file_rel,
                        line_number=idx,
                        code_snippet=stripped,
                        fix_suggestion="Remove conversational comment before pushing to production.",
                        auto_fixable=True,
                    )
                )
                break

    return issues
